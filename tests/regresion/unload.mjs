import fs from 'fs';
import * as T from './three-stub.mjs';
const geo = JSON.parse(fs.readFileSync('../../public/data/jujuy-departamentos.geojson', 'utf8'));
const susq = geo.features.find((f) => f.properties.nombre === 'Susques').geometry;
const { createEscenasLayer } = await import('../../src/components/Map3D/SceneManager.js');
let NOW = 0; Object.defineProperty(globalThis.performance, 'now', { value: () => NOW, configurable: true });
let zoom = 12.5, far = false;
const layer = createEscenasLayer({ onPick() {} });
const map = { getZoom: () => zoom, getCanvas: () => ({ clientWidth: 1200, clientHeight: 700 }), project: () => (far ? { x: 99999, y: 99999 } : { x: 600, y: 350 }), queryTerrainElevation: () => 3800, triggerRepaint() {} };
layer.onAdd(map, null); layer.setGeometries({ susques: susq });
const M = new Float64Array(16); M[0] = M[5] = M[10] = M[15] = 1;
const draws = () => { T.captured.length = 0; layer.render(null, M); return T.captured.length; };
let disposed = 0; const od = T.Material.prototype.dispose; T.Material.prototype.dispose = function () { disposed++; return od.call(this); };
const out = [];
NOW = 0; out.push(['visible', draws()]);
far = true; NOW = 10000; out.push(['fuera de cámara (10 s)', draws()]);
NOW = 25000; out.push(['fuera de cámara (25 s) -> se descarga', draws()]); console.log('materiales liberados tras 25 s fuera de cámara:', disposed);
far = false; NOW = 26000; out.push(['vuelve a verse -> se reconstruye', draws()]);
zoom = 6; NOW = 60000; out.push(['alejado a vista provincial (60 s)', draws()]);
zoom = 12.5; NOW = 61000; out.push(['vuelve a acercarse', draws()]);
out.forEach(([k, v]) => console.log(String(k).padEnd(42), 'escenas dibujadas:', v));
layer.onRemove(); console.log('onRemove OK (liberó escenas y geometrías compartidas)');
